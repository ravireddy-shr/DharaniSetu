// ---- Citizen's parcels (linked to citizens by state and id) ----
export const CITIZEN_PARCEL_IDS = ['AP-CHI-001', 'AP-CHI-002', 'AP-CHI-003'];

export function getParcelsForCitizen(citizenState?: string, citizenName?: string, citizenEmail?: string, customParcels?: LandParcel[]): LandParcel[] {
  const pool = (customParcels && customParcels.length > 0) ? customParcels : DEMO_PARCELS;
  const norm = (s?: string) => (s || '').toLowerCase().replace(/[^a-z0-9]/g, '');

  // 1. If citizen has an email with a parcel ID or matching recorded owner
  if (citizenEmail) {
    const cleanEmail = citizenEmail.trim().toLowerCase();
    const citizen = DEMO_FARMER_CITIZENS.find(f => f.email.toLowerCase() === cleanEmail);
    if (citizen) {
      const citizenNorm = norm(citizen.name);
      // Find all parcels where recordedOwner matches this citizen, or matches this citizen's primary parcelId
      const matches = pool.filter(p =>
        p.id === citizen.parcelId ||
        norm(p.recordedOwner) === citizenNorm ||
        (citizenNorm.length >= 4 && norm(p.recordedOwner).includes(citizenNorm))
      );
      if (matches.length > 0) return matches;
      const direct = pool.find(p => p.id === citizen.parcelId);
      if (direct) return [direct];
    }
  }

  // 2. If citizen name provided, match recordedOwner
  if (citizenName) {
    const nameNorm = norm(citizenName);
    if (nameNorm.length > 0) {
      // Exact normalized match
      const exact = pool.filter(p => norm(p.recordedOwner) === nameNorm);
      if (exact.length > 0) return exact;

      // Partial match
      const partial = pool.filter(p => {
        const ownerNorm = norm(p.recordedOwner);
        return ownerNorm.includes(nameNorm) || (nameNorm.length >= 4 && nameNorm.includes(ownerNorm));
      });
      if (partial.length > 0) return partial;
    }
  }

  // 3. Fallback: single sample parcel for test/demo accounts, never entire state
  if (citizenState) {
    const stateMatch = pool.find(p => p.stateId === citizenState);
    if (stateMatch) return [stateMatch];
  }

  return [pool[0]];
}



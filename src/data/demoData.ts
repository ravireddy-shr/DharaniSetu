// Find appropriate Tahsildar for an application automatically
export function getAssignedTahsildarForMandal(mandalId: string): OfficerProfile {
  const officers = DEMO_OFFICERS.filter(o => o.jurisdictionMandal === mandalId);
  if (officers.length > 0) {
    const tahsildarOfficer = officers.find(o => o.department === 'Tahsildar') || officers.find(o => o.department === 'Revenue');
    return tahsildarOfficer || officers[0];
  }
  // Fallback to primary demo Tahsildar (OFC-AP-02) or first officer
  const defaultTahsildar = DEMO_OFFICERS.find(o => o.department === 'Tahsildar');
  return defaultTahsildar || DEMO_OFFICERS[0];
}
